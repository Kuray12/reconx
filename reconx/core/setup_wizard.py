"""Interactive .env setup wizard."""

from __future__ import annotations

from reconx.core import console
from reconx.core.config import ENV_FILE

TEMPLATE = """# ReconX configuration (generated by setup wizard)

OPERATOR_NAME={operator}

TELEGRAM_BOT_TOKEN={tg_token}
TELEGRAM_CHAT_ID={tg_chat}

SMTP_HOST={smtp_host}
SMTP_PORT={smtp_port}
SMTP_USER={smtp_user}
SMTP_PASSWORD={smtp_password}
EMAIL_FROM={email_from}
EMAIL_TO={email_to}
"""


def _ask(prompt: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    try:
        value = console.console.input(f"[bold cyan]{prompt}{suffix}> [/]").strip()
    except EOFError:
        value = ""
    return value or default


def run_setup() -> None:
    """Collect settings and write them to .env."""
    console.rule("Setup Configuration")
    console.warn(
        "Isi hanya domain/channel milik Anda sendiri. Target scan diinput "
        "langsung saat memilih Deep Scan."
    )
    console.plain("")

    operator = _ask("Nama operator (masuk ke laporan)", "")

    console.plain("")
    console.plain("[dim]Notifikasi opsional - kosongkan bila tidak dipakai.[/]")
    tg_token = _ask("Telegram bot token", "")
    tg_chat = _ask("Telegram chat id", "")
    smtp_host = _ask("SMTP host", "")
    smtp_port = _ask("SMTP port", "587")
    smtp_user = _ask("SMTP user", "")
    smtp_password = _ask("SMTP password", "")
    email_from = _ask("Email pengirim", "")
    email_to = _ask("Email tujuan (milik Anda sendiri)", "")

    ENV_FILE.write_text(
        TEMPLATE.format(
            operator=operator,
            tg_token=tg_token,
            tg_chat=tg_chat,
            smtp_host=smtp_host,
            smtp_port=smtp_port,
            smtp_user=smtp_user,
            smtp_password=smtp_password,
            email_from=email_from,
            email_to=email_to,
        ),
        encoding="utf-8",
    )
    console.ok(f"Konfigurasi ditulis ke {ENV_FILE}")
    console.plain("      [dim]Jalankan ulang tool agar konfigurasi baru terbaca.[/]")
